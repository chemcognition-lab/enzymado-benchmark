SCRIPTS_REL = "embedding_scripts"


def generate(fasta_path: Path, output_sh: Path, emb_dir: str, git_root: Path) -> None:
    fasta_rel = fasta_path.resolve().relative_to(git_root)

    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by generate_embedding_sh.py",
        "# Run from the git root directory",
        f'SCRIPTS="{SCRIPTS_REL}"',
        "",
        f"# {fasta_rel}",
    ]

    for model_key, m in MODELS.items():
        out_rel = Path(emb_dir) / f"{model_key}_shards"
        lines.append(f"conda run -n {m['env']} python $SCRIPTS/{m['script']} \\")
        lines.append(f"    -i {fasta_rel} -o {out_rel} --model {m['model']}")
        lines.append("")

    output_sh.parent.mkdir(parents=True, exist_ok=True)
    with open(output_sh, "w") as f:
        f.write("\n".join(lines) + "\n")
    output_sh.chmod(0o755)
    print(f"Shell script written to: {output_sh}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Generate a shell script that embeds every unique protein sequence once "
            "per model. Example: python generate_embedding_sh.py "
            "--fasta data/fastas/protein_sequences_unique.fasta "
            "--output_sh scripts/run_embeddings.sh"
        )
    )
    parser.add_argument("--fasta", required=True, type=str,
                        help="Path to the deduplicated protein-sequence FASTA "
                             "(see make_fasta_from_unique_sequences.py).")
    parser.add_argument("--output_sh", required=True, type=str,
                        help="Output path for the generated shell script")
    parser.add_argument("--emb_dir", required=False, type=str,
                        default="data/embeddings/protein_sequences_unique",
                        help="Root directory for embeddings (relative to git root). "
                             "Default: data/embeddings/protein_sequences_unique")
    parser.add_argument("--git_root", required=False, type=str, default=".",
                        help="Repository root, used to make paths in the .sh relative. "
                             "Default: current directory.")
    args = parser.parse_args()

    generate(
        Path(args.fasta).resolve(),
        Path(args.output_sh).resolve(),
        args.emb_dir,
        Path(args.git_root).resolve(),
    )


if __name__ == "__main__":
    main()
