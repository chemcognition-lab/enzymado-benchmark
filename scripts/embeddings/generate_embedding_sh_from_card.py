SCRIPTS_REL = "embedding_scripts"
SECTION_KEYS = ("properties", "real_case")


def generate(card_path: Path, output_sh: Path, fasta_dir: Path,
             emb_dir: str, update_card: bool):

    with open(card_path) as f:
        card = json.load(f)

    git_root = card_path.parent
    updated_card = copy.deepcopy(card)

    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by generate_embedding_sh_from_card.py",
        "# Run from the git root directory",
        f'SCRIPTS="{SCRIPTS_REL}"',
        "",
    ]

    for section_name in SECTION_KEYS:
        for task_name, task in card.get(section_name, {}).items():
            lines.append(f"# {'─' * 68}")
            lines.append(f"# Section: {section_name} / {task_name}")
            lines.append(f"# {'─' * 68}")

            for ds_idx, dataset in enumerate(task["datasets"]):
                dataset_id = dataset["dataset_id"]
                fasta_rel  = (fasta_dir / f"{dataset_id}.fasta").relative_to(git_root)

                lines.append(f"\n# {dataset_id}")
                embeddings_meta = {}

                for model_key, m in MODELS.items():
                    out_rel = Path(emb_dir) / section_name / task_name / dataset_id / f"{model_key}.h5"

                    lines.append(
                        f"conda run -n {m['env']} python $SCRIPTS/{m['script']} \\"
                    )
                    lines.append(f"    -i {fasta_rel} -o {out_rel} --model {m['model']}")
                    lines.append("")

                    embeddings_meta[model_key] = {
                        "path":          str(out_rel),
                        "embedding_dim": m["dim"],
                    }

                ds_updated = updated_card[section_name][task_name]["datasets"][ds_idx]
                reordered = {}
                for k, v in ds_updated.items():
                    reordered[k] = v
                    if k == "schema":
                        reordered["embeddings"] = embeddings_meta
                updated_card[section_name][task_name]["datasets"][ds_idx] = reordered

    # Write shell script
    output_sh.parent.mkdir(parents=True, exist_ok=True)
    with open(output_sh, "w") as f:
        f.write("\n".join(lines) + "\n")
    output_sh.chmod(0o755)
    print(f"Shell script written to: {output_sh}")

    # Optionally update card
    if update_card:
        with open(card_path, "w") as f:
            json.dump(updated_card, f, indent=2)
        print(f"benchmark_card.json updated with embedding metadata")


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Generate an embedding shell script from benchmark_card.json and "
            "optionally update the card with embedding paths and dimensions. "
            "Example: python generate_embedding_sh_from_card.py "
            "--card benchmark_card.json --output_sh scripts/run_embeddings.sh --update_card"
        )
    )
    parser.add_argument("--card", required=True, type=str,
                        help="Path to benchmark_card.json")
    parser.add_argument("--output_sh", required=True, type=str,
                        help="Output path for the generated shell script")
    parser.add_argument("--fasta_dir", required=False, type=str, default=None,
                        help="Directory containing FASTA files. "
                             "Default: data/fastas/ relative to the card file.")
    parser.add_argument("--emb_dir", required=False, type=str,
                        default="data/embeddings",
                        help="Root directory for embeddings (relative to git root). "
                             "Default: data/embeddings")
    parser.add_argument("--update_card", action="store_true",
                        help="Update benchmark_card.json with embedding paths and dimensions.")
    args = parser.parse_args()

    card_path  = Path(args.card).resolve()
    output_sh  = Path(args.output_sh).resolve()
    fasta_dir  = Path(args.fasta_dir).resolve() if args.fasta_dir else card_path.parent / "data" / "fastas"

    generate(card_path, output_sh, fasta_dir, args.emb_dir, args.update_card)


if __name__ == "__main__":
    main()
